"""Provisional bridge contract, independent of any particular reasoning model.

This validates messages, not their translation or semantic truth. It performs
no network requests and never executes a task. Model adapters remain separate.
"""
import re
from chat import validate_response
from json_output import clean, dumps, loads

PROTOCOL = 'input.bridge/0.1'
TASKS = ('answer', 'calculate', 'summarize', 'compare', 'plan')
KEY = re.compile(r'^[a-z][a-z0-9_]{0,31}$')
ID = re.compile(r'^[a-zA-Z0-9_-]{1,64}$')

def _text(value, maximum=4000, empty=False):
    if not isinstance(value, str) or len(value)>maximum or (not empty and not value.strip()):
        raise ValueError('Bridge text is missing or too long')

def _base(value, kind, fields):
    # Do not silently rename fields or alter identifiers crossing the boundary.
    value = clean(value, simplify=False)
    if not isinstance(value, dict) or set(value)!=set(fields):
        raise ValueError('Unexpected bridge fields')
    if value['protocol']!=PROTOCOL or value['type']!=kind:
        raise ValueError('Incompatible bridge protocol or message type')
    if not isinstance(value['id'],str) or not ID.fullmatch(value['id']):
        raise ValueError('Invalid request id')
    missing=value['missing']
    if not isinstance(missing,list) or len(missing)>32 or any(not isinstance(k,str) or not KEY.fullmatch(k) for k in missing) or len(set(missing))!=len(missing):
        raise ValueError('Missing fields must be distinct simple keys')
    return value

def validate_request(value):
    value=_base(value,'request',('protocol','id','type','status','task','goal','data','constraints','context','missing'))
    if value['task'] not in TASKS or value['status'] not in ('ready','clarify'):
        raise ValueError('Unsupported task or request status')
    _text(value['goal'])
    for field in ('data','context'):
        if not isinstance(value[field],dict) or len(value[field])>64:
            raise ValueError('Data and context must be bounded objects')
    constraints=value['constraints']
    if not isinstance(constraints,list) or len(constraints)>32:
        raise ValueError('Constraints must be a bounded list')
    for constraint in constraints:
        if not isinstance(constraint,dict) or set(constraint)!={'key','op','value'}:
            raise ValueError('Invalid constraint')
        if not isinstance(constraint['key'],str) or not KEY.fullmatch(constraint['key']) or constraint['op'] not in ('eq','lte','gte','in'):
            raise ValueError('Invalid constraint key or operator')
        if constraint['op']=='in' and not isinstance(constraint['value'],list):
            raise ValueError('The in operator requires a list')
    if bool(value['missing'])!=(value['status']=='clarify'):
        raise ValueError('A clarification must list the missing information')
    return value

def validate_result(value, request=None):
    value=_base(value,'result',('protocol','id','type','status','answer','values','missing'))
    if value['status'] not in ('ok','clarify','error'):
        raise ValueError('Unsupported result status')
    _text(value['answer'])
    # Keep the same scalar value contract as the public French response.
    validate_response({'texte':'Validation','valeurs':value['values']})
    if value['status']=='clarify' and not value['missing'] or value['status']=='ok' and value['missing']:
        raise ValueError('Result status and missing fields disagree')
    if request is not None:
        request=validate_request(request)
        if value['id']!=request['id']:
            raise ValueError('Result belongs to a different request')
        if request['status']!='ready':
            raise ValueError('A request awaiting clarification cannot be dispatched')
    return value

def encode_request(value):
    request=validate_request(value)
    if request['status']!='ready':
        raise ValueError('Ask the user for clarification before dispatch')
    return dumps(request,simplify=False)

def decode_result(raw, request):
    return validate_result(loads(raw),request)

def french_response(result, text, request=None):
    """Attach French rendering while copying the backend's typed values.

    Translation quality and factual consistency of text need separate tests.
    Values are never regenerated by the renderer.
    """
    result=validate_result(result,request)
    return validate_response({'texte':text,'valeurs':loads(dumps(result['values'],simplify=False))})
